#!/usr/bin/env python3
"""
make_run.py -- The #1101 English run: corpus/sentences.tsv -> the bench's corpus and run files.

Writes, from `corpus/sentences.tsv` (what the typist means, what they type, and the
category of each slip):

  corpus/en-us.txt   the intended sentences, one per line (the bench's `<lang>.txt`)
  corpus/en-us.keys  the typed sentences, one per line
  runs/en-us.tsv     one row per tap, the format of tools/keyboard-bench/runs/

Every tap lands on the centre of the key typed, as in the bench's typo runs, except a
neighbour-key slip (category N): its wrong letter lands 0.3 of the way from the wrong
key's centre towards the key the typist meant, inside the wrong key, which is where a
thumb that misses lands. Intervals follow make_runs.py's rhythm (170 +- 40 ms, at least
60 ms), from a fixed seed, so rerunning rewrites the same files byte for byte.

Usage: python3 -I docs/research/1101-english-autocorrect/make_run.py
"""

import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
SEED = "1101-en-us"
TOWARDS = 0.3
ROWS = ["qwertyuiop", "asdfghjkl", "zxcvbnm"]
# Horizontal start of each row, in key widths: the QWERTY stagger.
STAGGER = [0.0, 0.5, 1.5]
POS = {c: (STAGGER[r] + i, r) for r, row in enumerate(ROWS) for i, c in enumerate(row)}


def neighbour_offset(intended, typed):
    """The offset of the one wrong letter of a neighbour slip, towards the key meant."""
    diffs = [i for i, (a, b) in enumerate(zip(intended, typed)) if a != b]
    if len(intended) != len(typed) or len(diffs) != 1:
        raise SystemExit(f"{typed!r} is not a one-letter substitution of {intended!r}")
    i = diffs[0]
    (wx, wy), (ix, iy) = POS[typed[i]], POS[intended[i]]
    if max(abs(ix - wx), abs(iy - wy)) > 1:
        raise SystemExit(f"{typed[i]!r} is not next to {intended[i]!r}")
    return i, TOWARDS * (ix - wx), TOWARDS * (iy - wy)


def main():
    rows = []
    with open(os.path.join(HERE, "corpus", "sentences.tsv"), encoding="utf-8") as f:
        next(f)
        for line in f:
            n, intended, typed, slips = (line.rstrip("\n").split("\t") + [""])[:4]
            rows.append((int(n), intended, typed, dict(s.split(":") for s in slips.split())))
    rng = random.Random(SEED)
    taps = []
    for index, (n, intended, typed, slips) in enumerate(rows):
        meant, got = intended.split(), typed.split()
        if len(meant) != len(got):
            raise SystemExit(f"sentence {n}: typed and intended differ in word count")
        for word, cat in slips.items():
            if word not in got:
                raise SystemExit(f"sentence {n}: slip {word!r} is not typed")
        t = 0
        tap = 0
        for m, g in zip(meant, got):
            special = neighbour_offset(m.replace("'", ""), g) if slips.get(g) == "N" else None
            for i, ch in enumerate(list(g) + ["space"]):
                dx, dy = (special[1], special[2]) if special and i == special[0] else (0.0, 0.0)
                if tap > 0:
                    t += max(60, round(rng.gauss(170, 40)))
                taps.append(f"{index}\t{tap}\t{ch}\t{dx:.4f}\t{dy:.4f}\t{t}")
                tap += 1
    with open(os.path.join(HERE, "corpus", "en-us.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(r[1] for r in rows) + "\n")
    with open(os.path.join(HERE, "corpus", "en-us.keys"), "w", encoding="utf-8") as f:
        f.write("\n".join(r[2] for r in rows) + "\n")
    with open(os.path.join(HERE, "runs", "en-us.tsv"), "w", encoding="utf-8") as f:
        f.write(f"# generated by make_run.py: seed {SEED}, key centres, neighbour slips {TOWARDS} towards the key meant\n")
        f.write("sentence\ttap\tkey\tdx\tdy\tt_ms\n")
        f.write("\n".join(taps) + "\n")
    print(f"{len(rows)} sentences, {len(taps)} taps")


if __name__ == "__main__":
    main()
