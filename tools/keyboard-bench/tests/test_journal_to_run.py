"""journal_to_run.py: an exported typing journal (#1001) becomes a touch run (#954).

Run: python3 -I -m unittest discover -s tools/keyboard-bench/tests
"""
import importlib.util
import os
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("journal_to_run", os.path.join(HERE, "..", "journal_to_run.py"))
journal_to_run = importlib.util.module_from_spec(spec)
spec.loader.exec_module(journal_to_run)

PREFIX = "[2026-11-20T10:00:00Z] DEBUG   [keyboard] <keyboard> "


def tap(key, dt="150", dx="+0.1000", dy="-0.2000", kb="fr-azerty"):
    return f"{PREFIX}TJ TAP k={key} dx={dx} dy={dy} dt={dt} kb={kb}"


SESSION = [
    "Dictus Debug Log",
    "[2026-11-20T09:59:59Z] INFO    [keyboard] keyboardDidAppear instance=1",
    f"{PREFIX}TJ FIELD kb=fr-azerty",
    tap("t", dt="-"), tap("r"), tap("e"), tap("s"), tap("space", dx="-0.0874", dy="+0.4725"),
    f'{PREFIX}TJ WORD #1 typed="tres" prev=nil final="Très" outcome=autocorrected by=space previews=3',
    f'{PREFIX}TJ WHY #1 AUTOCORRECT branch=accent orig="tres" corr="très" prev=nil',
    tap("b"), tap("backspace"), tap("shift"), tap("123"), tap("1"), tap("space"), tap("o"),
    tap("return"),
    tap("a", dt="900"), tap("accent"),
    f'{PREFIX}TJ BARTAP #2 slot=1 word="à" bar=candidates["a","à"]',
    f"{PREFIX}TJ REPEAT k=backspace",
    f"{PREFIX}TJ FIELD kb=en-qwerty",
    tap("h", dt="-", kb="en-qwerty"), tap("i", kb="en-qwerty"),
]


class JournalToRunTests(unittest.TestCase):

    def test_sentences_split_at_fields_returns_and_languages(self):
        sentences, _ = journal_to_run.parse(SESSION)
        self.assertEqual([(s.lang, [t[0] for t in s.taps]) for s in sentences], [
            ("fr", ["t", "r", "e", "s", "space", "b", "backspace", "shift", "o"]),
            ("fr", ["a", "accent"]),
            ("en", ["h", "i"]),
        ])

    def test_offsets_and_times_are_kept(self):
        sentences, _ = journal_to_run.parse(SESSION)
        first = sentences[0].taps
        self.assertEqual(first[4], ("space", -0.0874, 0.4725, 600.0))
        self.assertEqual([t[3] for t in first[:4]], [0.0, 150.0, 300.0, 450.0])

    def test_what_a_replay_cannot_type_is_counted(self):
        sentences, skipped = journal_to_run.parse(SESSION)
        self.assertEqual(dict(skipped), {"symbols page": 3, "bar taps": 1, "held-backspace repeats": 1})
        self.assertEqual([s.unreplayable for s in sentences], [3, 2, 0])

    def test_corpus_lines_hold_the_device_words_one_per_space(self):
        sentences, _ = journal_to_run.parse(SESSION)
        self.assertEqual([journal_to_run.corpus_line(s) for s in sentences], ["très -", "à", "-"])

    def test_written_run_reads_like_the_committed_runs(self):
        sentences, _ = journal_to_run.parse(SESSION)
        with tempfile.TemporaryDirectory() as out:
            _, names = journal_to_run.write(sentences, "dictus-logs.txt", out)
            self.assertEqual(names, ["en-journal", "fr-journal"])
            with open(os.path.join(out, "runs", "fr-journal.tsv"), encoding="utf-8") as f:
                rows = f.read().splitlines()
            with open(os.path.join(out, "corpus", "fr-journal.txt"), encoding="utf-8") as f:
                corpus = f.read().splitlines()
        self.assertEqual(rows[:3], ["# generated by journal_to_run.py from dictus-logs.txt",
                                    "sentence\ttap\tkey\tdx\tdy\tt_ms",
                                    "0\t0\tt\t0.1000\t-0.2000\t0"])
        self.assertEqual(rows[-2:], ["1\t0\ta\t0.1000\t-0.2000\t0", "1\t1\taccent\t0.1000\t-0.2000\t150"])
        self.assertEqual(corpus, ["très -", "à"])

    def test_quotes_in_words_are_unescaped(self):
        lines = [f"{PREFIX}TJ FIELD kb=en-qwerty", tap("i", dt="-", kb="en-qwerty"),
                 f'{PREFIX}TJ WORD #1 typed="Im" prev=nil final="I\\"m" outcome=autocorrected by=space previews=0']
        sentences, _ = journal_to_run.parse(lines)
        self.assertEqual(sentences[0].words, ['I"m'])


if __name__ == "__main__":
    unittest.main()
