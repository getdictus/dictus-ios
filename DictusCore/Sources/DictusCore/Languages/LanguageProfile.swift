// DictusCore/Sources/DictusCore/Languages/LanguageProfile.swift
// Pure data describing the per-language inputs used by the autocorrect pipeline.
import Foundation

/// Pure-data per-language profile consumed by autocorrect helpers.
///
/// One profile per supported language, declared in `Languages/<Lang>.swift`.
/// The struct holds *only data* — no algorithms. Algorithms live in
/// `TextCorrection/` and read profiles via `SupportedLanguage.profile`.
///
/// WHY pure data:
/// Separating per-language data from the algorithm makes the algorithm testable
/// in isolation (no bridge dependency) and adding a new language a matter of
/// authoring one new file. See ADR 0001 for the policy on what populates these
/// fields on first ship vs. post-launch.
public struct LanguageProfile: Sendable {
    /// BCP-47 short code (e.g. "fr", "en", "es", "de"). Matches `SupportedLanguage.rawValue`.
    public let code: String

    /// Localized display name shown in the settings picker (e.g. "Français").
    public let displayName: String

    /// Two-letter uppercase code shown on the keyboard toolbar language switcher.
    public let shortCode: String

    /// Default keyboard layout for this language (AZERTY for French, QWERTY for others).
    public let defaultLayout: LayoutType

    /// Spacebar label in this language's convention (e.g. "espace", "space", "Leertaste").
    public let spaceName: String

    /// Return key label in this language's convention (e.g. "retour", "return", "Eingabe").
    public let returnName: String

    /// Hard-coded must-correct map: lowercase input → forced correction.
    /// Used for words that are *never* valid in this language without their accent
    /// or contraction (e.g. French `ca` → `ça`). Empty for languages onboarded
    /// without native-speaker curation. See ADR 0001.
    public let overrides: [String: String]

    /// Must-correct map that applies only after a given previous word: lowercase
    /// previous word → (lowercase input → forced correction). For valid words that
    /// are never valid in that position, such as French `il ma` → `il m'a` (#500):
    /// a possessive cannot follow a subject pronoun. Empty unless curated.
    public let contextOverrides: [String: [String: String]]

    /// Accent variants generated by `AccentExpander` when a typed word is missing
    /// from the dictionary. Keyed by base letter, value is the list of accents
    /// the algorithm should try at that position.
    public let accentMap: [Character: [Character]]

    /// Apostrophe contraction prefixes used by `ContractionExpander`
    /// (e.g. French `["l'", "d'", "qu'"]`). Each prefix already includes the
    /// apostrophe. Empty for languages without contractions (English, Spanish).
    public let contractionPrefixes: [String]

    /// Elisions typed with a wrong prefix, a key in place of the apostrophe, or a
    /// space (#1006). nil for languages without elision.
    public let elisionRepair: ElisionRepair?

    /// The prefixes that elide and the letters an elided word may start with: French
    /// `d'votre` is never a word. nil for languages without elision.
    public let elisionOnset: ElisionOnset?

    /// Length-changing substring substitutions tried by `AccentExpander` when a
    /// typed word isn't a stronger match in the dictionary. Each rule is
    /// `(from, to)` where `from` is the substring to find and `to` is its
    /// replacement. The German `("ss", "ß")` rule lets users typing on a US
    /// keyboard still reach `straße`/`weiß`/`groß` without long-pressing `s`.
    /// Empty for languages without length-changing collapses.
    public let collapseRules: [(from: String, to: String)]

    /// Where an accented past participle is expected, for `restoreAccents` (#994).
    /// nil for languages whose participles carry no accent (Spanish `llegado`) or
    /// that nobody has written the list for.
    public let participleContext: ParticipleContext?

    /// The lowercase one-letter words of the language, French `a`, `à` and `y` (#977).
    /// Any other lone letter is corrected to a neighbouring key that is one of them, or
    /// kept (`LoneLetterCorrection`). nil for languages nobody has written them for,
    /// which leaves every lone letter to the dictionary, as before.
    public let loneLetterWords: Set<String>?

    /// Lowercase words after which a lone letter is the letter itself, never a slip:
    /// French determiners and `lettre` (`le h aspiré`, `un z`, `la lettre b`, #977).
    /// Read by `LoneLetterCorrection` only. Empty where `loneLetterWords` is nil.
    public let loneLetterMarkers: Set<String>

    /// Known misspellings, lowercase, with their correct form: the entries
    /// `tools/misspellings/` removed from the word list (`teh` → `the`). Read
    /// with `overrides`, and kept apart from it because it is generated from a
    /// public list rather than curated. See `KnownMisspellings.swift`.
    public let misspellings: [String: String]

    /// Contractions typed without their apostrophe that are also words on their
    /// own (`ill` for `I'll`), corrected only where the words before call for
    /// the contraction. See `ContextualContraction`.
    public let contextualContractions: [ContextualContraction]
    /// Words with two correct spellings that the words before them choose
    /// between, such as French `a` and `à` (#501). Empty for every other language,
    /// so nothing of this kind fires outside French.
    public let contextualHomographs: [ContextualHomograph]

    /// What a held letter key offers, keyed by lowercase base letter, as Apple's keyboard
    /// for this language shows it (#1042). Variants only, lowercase, nearest the base
    /// first: the popup puts the base itself in front, and shift or caps lock capitalizes
    /// them (`AccentedCharacters.shifted`). A letter not listed holds nothing. Read
    /// through `AccentedCharacters.mappings(for:layout:)`, which adds `lettersWithOwnKey`.
    public let longPressAccents: [String: [String]]

    /// Letters Apple's layout for this language gives keys of their own (German ä ö ü,
    /// Spanish ñ), so `longPressAccents` leaves them out. On a layout without that key,
    /// Apple's keyboard holds each one right after its base letter, and so does Dictus.
    public let lettersWithOwnKey: [String]

    public init(
        code: String,
        displayName: String,
        shortCode: String,
        defaultLayout: LayoutType,
        spaceName: String,
        returnName: String,
        overrides: [String: String],
        contextOverrides: [String: [String: String]] = [:],
        accentMap: [Character: [Character]],
        contractionPrefixes: [String],
        elisionRepair: ElisionRepair? = nil,
        elisionOnset: ElisionOnset? = nil,
        collapseRules: [(from: String, to: String)] = [],
        participleContext: ParticipleContext? = nil,
        loneLetterWords: Set<String>? = nil,
        loneLetterMarkers: Set<String> = [],
        misspellings: [String: String] = [:],
        contextualContractions: [ContextualContraction] = [],
        contextualHomographs: [ContextualHomograph] = [],
        longPressAccents: [String: [String]],
        lettersWithOwnKey: [String] = []
    ) {
        self.code = code
        self.displayName = displayName
        self.shortCode = shortCode
        self.defaultLayout = defaultLayout
        self.spaceName = spaceName
        self.returnName = returnName
        self.overrides = overrides
        self.contextOverrides = contextOverrides
        self.accentMap = accentMap
        self.contractionPrefixes = contractionPrefixes
        self.elisionRepair = elisionRepair
        self.elisionOnset = elisionOnset
        self.collapseRules = collapseRules
        self.participleContext = participleContext
        self.loneLetterWords = loneLetterWords
        self.loneLetterMarkers = loneLetterMarkers
        self.misspellings = misspellings
        self.contextualContractions = contextualContractions
        self.contextualHomographs = contextualHomographs
        self.longPressAccents = longPressAccents
        self.lettersWithOwnKey = lettersWithOwnKey
    }
}

extension SupportedLanguage {
    /// The data profile for this language. Used by the autocorrect helpers in
    /// `TextCorrection/` and (eventually) by the keyboard layout/picker code.
    public var profile: LanguageProfile {
        switch self {
        case .french: return frenchProfile
        case .english: return englishProfile
        case .spanish: return spanishProfile
        case .german: return germanProfile
        }
    }
}
